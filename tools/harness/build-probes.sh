#!/bin/bash
# Build each probe's single state file (MUGEN may not merge [Statedef -2]
# blocks spread over several files). Order matters: a ChangeState in -2 ends
# that tick's -2 pass, so it is header + clock, then the script, then capture.
set -euo pipefail
D=$(cd "$(dirname "$0")" && pwd)/overlay/chars/probe
CAP="$D/capture.st"
SPLIT=$(grep -n '^; ---- State capture' "$CAP" | cut -d: -f1)
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / script.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/script.st"
  echo
  tail -n +"$SPLIT" "$CAP"
} > "$D/probe.st"
echo "built $D/probe.st"

# probe720: kfm720's own [Statedef -2] holds only its "Diagonal" PosSet; since
# the first -2 wins, the capture file (loaded first) carries an exact copy.
{
  echo "; GENERATED by tools/harness/build-probes.sh - capture + kfm720's -2"
  head -n $((SPLIT - 1)) "$CAP"
  cat <<'DIAG'
[state -2, Diagonal]
type = posset
trigger1 = statetype != a
y = -((Pos x+Camerapos x)+20)/60*2.5

DIAG
  tail -n +"$SPLIT" "$CAP"
} > "$D/capture720.st"
echo "built $D/capture720.st"


# probecam: the scripted camera scenario.
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / camscript.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/camscript.st"
  echo
  tail -n +"$SPLIT" "$CAP"
} > "$D/probecam.st"
echo "built $D/probecam.st"

# probefx: projectile, helper and Random; its helper states go after -2.
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / fxscript.st / fxstates.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/fxscript.st"
  echo
  tail -n +"$SPLIT" "$CAP"
  echo
  cat "$D/fxstates.st"
} > "$D/probefx.st"
echo "built $D/probefx.st"

# probesuper: supers.
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / superscript.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/superscript.st"
  echo
  tail -n +"$SPLIT" "$CAP"
} > "$D/probesuper.st"
echo "built $D/probesuper.st"

# probeai: input/CPU driven, P1 records Random every tick.
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / aiscript.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/aiscript.st"
  echo
  tail -n +"$SPLIT" "$CAP"
} > "$D/probeai.st"
echo "built $D/probeai.st"

# probeko: a KO with KFM's crouching strong kick (Trip).
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / koscript.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/koscript.st"
  echo
  tail -n +"$SPLIT" "$CAP"
} > "$D/probeko.st"
echo "built $D/probeko.st"

# probepos: projectile origins by postype.
{
  echo "; GENERATED by tools/harness/build-probes.sh - edit capture.st / posscript.st"
  head -n $((SPLIT - 1)) "$CAP"
  cat "$D/posscript.st"
  echo
  tail -n +"$SPLIT" "$CAP"
} > "$D/probepos.st"
echo "built $D/probepos.st"
