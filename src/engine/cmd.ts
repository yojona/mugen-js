// CMD command definitions and MUGEN 1.1's input pipeline.
//
// Reverse-engineered from mugen.exe (0x439f20 parser, 0x478610 producer,
// 0x4787e0/0x478b30 matcher) and checked with tools/harness:
//  - Every key that changes generates an event; each player consumes at most
//    one event per tick (a 30-entry ring), so simultaneous changes spread
//    over several ticks.
//  - Consuming an event turns it into entries of a 128-entry command queue:
//    a direction event pushes the release of the previous direction state and
//    the new state, read from the keys held *now*. A button press is held
//    back until a tick without an event (so x+y can combine); a release goes
//    in at once, with the time the key was held.
//  - Commands are matched against queue entries, newest first, only when an
//    entry is added; a match keeps the command active for buffer.time ticks.
//    '/' commands of one element are checked against the held keys every tick.

import { parseIni, getValue, findSection, unquote } from '../formats/text';

// Input bits (absolute directions; F/B depend on facing).
export const IN_U = 1;
export const IN_D = 2;
export const IN_L = 4;
export const IN_R = 8;
export const IN_A = 16;
export const IN_B = 32;
export const IN_C = 64;
export const IN_X = 128;
export const IN_Y = 256;
export const IN_Z = 512;
export const IN_S = 1024;

// MUGEN's element / event bits.
const K_U = 0x1000;
const K_F = 0x2000;
const K_D = 0x4000;
const K_B = 0x8000;
const DIR_BITS = 0x8f000;
const F_RELEASE = 0x10000; // '~' / key released
const F_HOLD = 0x20000; // '/'
const F_LOOSE = 0x40000; // '$'
const F_SYNTH = 0x100000; // generated by a facing change
const DIRS: Record<string, number> = { U: K_U, UF: K_U | K_F, UB: K_U | K_B, D: K_D, DF: K_D | K_F, DB: K_D | K_B, F: K_F, B: K_B, N: 0x80000 };
const BUTTONS: Record<string, number> = { a: 0x10, b: 0x20, c: 0x40, x: 0x80, y: 0x100, z: 0x200, s: 0x400 };

function intOr(s: string | undefined, d: number): number {
  const v = parseInt(s ?? '', 10);
  return Number.isNaN(v) ? d : v;
}

/** One command element: MUGEN's two words (bits/flags, and bit 0 = '>' strict). */
interface Element {
  bits: number;
  strict: boolean;
}

export interface Command {
  name: string;
  elements: Element[];
  time: number;
  bufferTime: number;
  /** Shared by commands with the same name. */
  slot: number;
}

export interface CommandSet {
  commands: Command[];
  /** Lowercased names, for validating `command = "x"` triggers. */
  names: Set<string>;
  /** MUGEN's command count: the numbering counter (indices run below it). */
  slots: number;
  /** Size of the command buffer (same as slots). */
  size: number;
}

export function parseCmd(text: string): CommandSet {
  const doc = parseIni(text);
  const defaults = findSection(doc, 'Defaults');
  const defTime = parseInt(getValue(defaults, 'command.time') ?? '15', 10) || 15;
  const defBuffer = parseInt(getValue(defaults, 'command.buffer.time') ?? '1', 10) || 1;
  const commands: Command[] = [];
  const slotOf = new Map<string, number>();
  let counter = 1;
  for (const sec of doc.sections) {
    if (sec.name.toLowerCase() !== 'command') continue;
    // Names are case-sensitive (strcmp): "26a" and "26A" are two labels.
    const name = unquote(getValue(sec, 'name') ?? '');
    const src = getValue(sec, 'command');
    if (!name || !src) continue;
    const elements = parseElements(src);
    if (!elements) continue;
    // mugen.exe 0x439920: names are numbered from 1 in order of first
    // appearance (duplicates share it); every "recovery" uses 0 but still
    // takes a number, a repeated one too. The AI's random command index runs
    // below the final counter.
    if (name === 'recovery') {
      slotOf.set(name, 0);
      counter++;
    } else if (!slotOf.has(name)) {
      slotOf.set(name, counter);
      counter++;
    }
    commands.push({
      name,
      elements,
      // char.c: Ini_GetInt overrides the defaults as written; buffer.time is only capped at 30.
      time: intOr(getValue(sec, 'time'), defTime),
      bufferTime: Math.min(30, intOr(getValue(sec, 'buffer.time'), defBuffer)),
      slot: slotOf.get(name)!,
    });
  }
  return { commands, names: new Set(slotOf.keys()), slots: counter, size: counter };
}

/** mugen.exe 0x439f20. Returns undefined if the command does not parse. */
function parseElements(src: string): Element[] | undefined {
  const out: Element[] = [];
  for (const raw of src.split(',')) {
    let s = raw.trim();
    if (!s) continue;
    let flags = 0;
    let strict = false;
    if (s.startsWith('>')) {
      strict = true;
      s = s.slice(1).trimStart();
    }
    if (s.startsWith('/')) {
      flags |= F_HOLD;
      s = s.slice(1).trimStart();
    }
    if (s.startsWith('~')) {
      flags |= F_RELEASE;
      const m = /^~(\d*)/.exec(s)!;
      // The charge time is stored above bit 20 with its two low bits cleared.
      if (m[1]) flags |= (parseInt(m[1], 10) & ~3) << 20;
      s = s.slice(m[0].length).trimStart();
    }
    if (s.startsWith('$')) {
      flags |= F_LOOSE;
      s = s.slice(1).trimStart();
    }
    let bits = 0;
    for (let part of s.split('+')) {
      part = part.trim();
      if (!part) continue;
      const v = DIRS[part] ?? (part.length > 1 ? DIRS[part.toUpperCase()] : undefined) ?? BUTTONS[part];
      if (v === undefined) return undefined;
      bits |= v;
    }
    if (!bits) return undefined;
    const el: Element = { bits: bits | flags, strict };
    // A repeated direction ("F, F") gets a release inserted in between, and
    // both become strict (0x43a04e).
    const prev = out[out.length - 1];
    if (prev && prev.bits === el.bits && el.bits & DIR_BITS) {
      out.push({ bits: prev.bits | F_RELEASE, strict: true });
      el.strict = true;
    }
    out.push(el);
  }
  return out.length ? out : undefined;
}

// ---------------------------------------------------------------------------
// Raw input history (absolute bits per tick), for engine-level checks.

export class InputHistory {
  private buf: Int32Array;
  private head = 0;
  private count = 0;

  constructor(readonly size = 128) {
    this.buf = new Int32Array(size);
  }

  push(bits: number): void {
    this.head = (this.head + 1) % this.size;
    this.buf[this.head] = bits;
    this.count = Math.min(this.count + 1, this.size);
  }

  /** Raw input `ago` ticks back (0 = current tick). Ticks before the start are 0. */
  raw(ago: number): number {
    if (ago >= this.count) return 0;
    return this.buf[(this.head - ago + this.size * 2) % this.size]!;
  }

  get length(): number {
    return this.count;
  }
}

