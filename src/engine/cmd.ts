// CMD command definitions and MUGEN 1.1's input pipeline.
//
// Reverse-engineered from mugen.exe (0x439f20 parser, 0x478610 producer,
// 0x4787e0/0x478b30 matcher) and checked with tools/harness:
//  - Every key that changes generates an event; each player consumes at most
//    one event per tick (a 30-entry ring), so simultaneous changes spread
//    over several ticks.
//  - Consuming an event turns it into entries of a 128-entry command queue:
//    a direction event pushes the release of the previous direction state and
//    the new state, read from the keys held *now*. A button press is held
//    back until a tick without an event (so x+y can combine); a release goes
//    in at once, with the time the key was held.
//  - Commands are matched against queue entries, newest first, only when an
//    entry is added; a match keeps the command active for buffer.time ticks.
//    '/' commands of one element are checked against the held keys every tick.

import { parseIni, getValue, findSection, unquote } from '../formats/text';

// Input bits (absolute directions; F/B depend on facing).
export const IN_U = 1;
export const IN_D = 2;
export const IN_L = 4;
export const IN_R = 8;
export const IN_A = 16;
export const IN_B = 32;
export const IN_C = 64;
export const IN_X = 128;
export const IN_Y = 256;
export const IN_Z = 512;
export const IN_S = 1024;

// MUGEN's element / event bits.
const K_U = 0x1000;
const K_F = 0x2000;
const K_D = 0x4000;
const K_B = 0x8000;
const DIR_BITS = 0x8f000;
const F_RELEASE = 0x10000; // '~' / key released
const F_HOLD = 0x20000; // '/'
const F_LOOSE = 0x40000; // '$'
const F_SYNTH = 0x100000; // generated by a facing change
const DIRS: Record<string, number> = { U: K_U, UF: K_U | K_F, UB: K_U | K_B, D: K_D, DF: K_D | K_F, DB: K_D | K_B, F: K_F, B: K_B };
const BUTTONS: Record<string, number> = { a: 0x10, b: 0x20, c: 0x40, x: 0x80, y: 0x100, z: 0x200, s: 0x400 };

/** One command element: MUGEN's two words (bits/flags, and bit 0 = '>' strict). */
interface Element {
  bits: number;
  strict: boolean;
}

export interface Command {
  name: string;
  elements: Element[];
  time: number;
  bufferTime: number;
  /** Shared by commands with the same name. */
  slot: number;
}

export interface CommandSet {
  commands: Command[];
  /** Lowercased names, for validating `command = "x"` triggers. */
  names: Set<string>;
  slots: number;
}

export function parseCmd(text: string): CommandSet {
  const doc = parseIni(text);
  const defaults = findSection(doc, 'Defaults');
  const defTime = parseInt(getValue(defaults, 'command.time') ?? '15', 10) || 15;
  const defBuffer = parseInt(getValue(defaults, 'command.buffer.time') ?? '1', 10) || 1;
  const commands: Command[] = [];
  const slotOf = new Map<string, number>();
  for (const sec of doc.sections) {
    if (sec.name.toLowerCase() !== 'command') continue;
    const name = unquote(getValue(sec, 'name') ?? '').toLowerCase();
    const src = getValue(sec, 'command');
    if (!name || !src) continue;
    const elements = parseElements(src);
    if (!elements) continue;
    if (!slotOf.has(name)) slotOf.set(name, slotOf.size);
    commands.push({
      name,
      elements,
      time: Math.max(1, parseInt(getValue(sec, 'time') ?? '', 10) || defTime),
      bufferTime: Math.max(1, Math.min(30, parseInt(getValue(sec, 'buffer.time') ?? '', 10) || defBuffer)),
      slot: slotOf.get(name)!,
    });
  }
  return { commands, names: new Set(slotOf.keys()), slots: slotOf.size };
}

/** mugen.exe 0x439f20. Returns undefined if the command does not parse. */
function parseElements(src: string): Element[] | undefined {
  const out: Element[] = [];
  for (const raw of src.split(',')) {
    let s = raw.trim();
    if (!s) continue;
    let flags = 0;
    let strict = false;
    if (s.startsWith('>')) {
      strict = true;
      s = s.slice(1).trimStart();
    }
    if (s.startsWith('/')) {
      flags |= F_HOLD;
      s = s.slice(1).trimStart();
    }
    if (s.startsWith('~')) {
      flags |= F_RELEASE;
      const m = /^~(\d*)/.exec(s)!;
      // The charge time is stored above bit 20 with its two low bits cleared.
      if (m[1]) flags |= (parseInt(m[1], 10) & ~3) << 20;
      s = s.slice(m[0].length).trimStart();
    }
    if (s.startsWith('$')) {
      flags |= F_LOOSE;
      s = s.slice(1).trimStart();
    }
    let bits = 0;
    for (let part of s.split('+')) {
      part = part.trim();
      if (!part) continue;
      const v = DIRS[part] ?? (part.length > 1 ? DIRS[part.toUpperCase()] : undefined) ?? BUTTONS[part];
      if (v === undefined) return undefined;
      bits |= v;
    }
    if (!bits) return undefined;
    const el: Element = { bits: bits | flags, strict };
    // A repeated direction ("F, F") gets a release inserted in between, and
    // both become strict (0x43a04e).
    const prev = out[out.length - 1];
    if (prev && prev.bits === el.bits && el.bits & DIR_BITS) {
      out.push({ bits: prev.bits | F_RELEASE, strict: true });
      el.strict = true;
    }
    out.push(el);
  }
  return out.length ? out : undefined;
}

// ---------------------------------------------------------------------------
// Raw input history (absolute bits per tick), for engine-level checks.

export class InputHistory {
  private buf: Int32Array;
  private head = 0;
  private count = 0;

  constructor(readonly size = 128) {
    this.buf = new Int32Array(size);
  }

  push(bits: number): void {
    this.head = (this.head + 1) % this.size;
    this.buf[this.head] = bits;
    this.count = Math.min(this.count + 1, this.size);
  }

  /** Raw input `ago` ticks back (0 = current tick). Ticks before the start are 0. */
  raw(ago: number): number {
    if (ago >= this.count) return 0;
    return this.buf[(this.head - ago + this.size * 2) % this.size]!;
  }

  get length(): number {
    return this.count;
  }
}

// ---------------------------------------------------------------------------
// MUGEN's per-player input pipeline.

/** Key indices in events: 1 U, 2 F, 3 D, 4 B, 5..11 a b c x y z s. */
const KEY_BITS = [0, K_U, K_F, K_D, K_B, 0x10, 0x20, 0x40, 0x80, 0x100, 0x200, 0x400];
const EV_RELEASE = 0x10;
const EV_SYNTH = 0x20;
/**
 * Absolute input bits in the order the harness (and so our replay) sends
 * simultaneous key changes: alphabetically by key name (a b c d l r s u x y z).
 */
const KEY_ORDER: [number, number | 'R' | 'L'][] = [
  [IN_A, 5], [IN_B, 6], [IN_C, 7], [IN_D, 3], [IN_L, 'L'], [IN_R, 'R'], [IN_S, 11], [IN_U, 1], [IN_X, 8], [IN_Y, 9], [IN_Z, 10],
];
const RING = 30;
const QUEUE = 128;

export class CommandInput {
  /** Held flags by key index (relative: index 2 = forward, 4 = back). */
  private held = new Uint8Array(12);
  private facingLeft = false;
  private prevRaw = 0;
  private ring: number[] = [];
  private dirState = 0;
  private pending = 0;
  private pressTime = new Int32Array(16);
  // Command queue.
  private qBits = new Int32Array(QUEUE);
  private qTime = new Int32Array(QUEUE);
  private qHold = new Int32Array(QUEUE);
  private qStart = 0;
  private qWrite = 0;
  private qRead = 0;
  /** Held keys as bits, snapshot at the start of the tick (0x650). */
  private heldBits = 0;
  private buffer: Uint8Array;
  private last: Float64Array;

  constructor(private set: CommandSet) {
    this.buffer = new Uint8Array(Math.max(1, set.slots));
    this.last = new Float64Array(Math.max(1, set.slots)).fill(-Infinity);
  }

  /**
   * One tick: facing-change events, this tick's key events, then the player's
   * update (one event consumed, queue matched). `raw` is the absolute input.
   */
  tick(raw: number, facing: number, time: number, frozen: boolean): void {
    this.syncFacing(facing < 0);
    this.keyEvents(raw);
    this.update(time, frozen);
  }

  /** Active command names (buffer > 0). */
  active(): Set<string> {
    const out = new Set<string>();
    for (const c of this.set.commands) if (this.buffer[c.slot]! > 0) out.add(c.name);
    return out;
  }

  private pushEvent(code: number): void {
    if (this.ring.length >= RING) this.ring.shift();
    this.ring.push(code);
    this.held[code & 0xf] = code & EV_RELEASE ? 0 : 1;
  }

  /** mugen.exe 0x477c40: turning around swaps a held forward/back key. */
  private syncFacing(left: boolean): void {
    if (left === this.facingLeft) return;
    const wasLeft = this.facingLeft;
    this.facingLeft = left;
    if (this.held[2] && this.held[4]) return;
    const first = wasLeft ? 2 : 4;
    const other = wasLeft ? 4 : 2;
    if (this.held[first]) {
      this.pushEvent(EV_SYNTH | EV_RELEASE | first);
      this.pushEvent(EV_SYNTH | other);
    } else if (this.held[other]) {
      this.pushEvent(EV_SYNTH | EV_RELEASE | other);
      this.pushEvent(EV_SYNTH | first);
    }
  }

  /** OS key events for what changed since last tick: releases, then presses. */
  private keyEvents(raw: number): void {
    const changed = raw ^ this.prevRaw;
    if (!changed) return;
    const idxOf = (k: number | 'R' | 'L') => (k === 'R' ? (this.facingLeft ? 4 : 2) : k === 'L' ? (this.facingLeft ? 2 : 4) : k);
    for (const [bit, k] of KEY_ORDER) if (changed & bit && !(raw & bit)) this.pushEvent(EV_RELEASE | idxOf(k));
    for (const [bit, k] of KEY_ORDER) if (changed & bit && raw & bit) this.pushEvent(idxOf(k));
    this.prevRaw = raw;
  }

  private heldDirs(): number {
    return (this.held[1] ? K_U : 0) | (this.held[2] ? K_F : 0) | (this.held[4] ? K_B : 0) | (this.held[3] ? K_D : 0);
  }

  /** mugen.exe 0x434db0 (input part). */
  /** Key event consumed this tick (0 if none). */
  lastEvent = 0;

  private update(time: number, frozen: boolean): void {
    const ev = this.ring.length ? this.ring.shift()! : 0;
    this.lastEvent = ev;
    let held = 0;
    for (let i = 1; i < 12; i++) if (this.held[i]) held |= KEY_BITS[i]!;
    this.heldBits = held;
    const floor = frozen ? 2 : 0;
    for (let i = 0; i < this.buffer.length; i++) {
      if (this.buffer[i]! > 0) {
        this.buffer[i]!--;
        if (this.buffer[i]! < floor) this.buffer[i] = floor;
      }
    }
    this.produce(ev, time);
    this.process(time);
  }

  private push(bits: number, time: number, hold: number): void {
    this.qBits[this.qWrite] = bits;
    this.qTime[this.qWrite] = time;
    this.qHold[this.qWrite] = hold;
    this.qWrite = (this.qWrite + 1) % QUEUE;
    if (this.qWrite === this.qStart) this.qStart = (this.qStart + 1) % QUEUE;
  }

  /** mugen.exe 0x478610: turn one key event (or none) into queue entries. */
  private produce(ev: number, time: number): void {
    let esi = 0;
    if (ev) {
      esi = KEY_BITS[ev & 0xf]!;
      if (ev & EV_RELEASE) esi |= F_RELEASE;
      if (ev & EV_SYNTH) esi |= F_SYNTH;
    }
    const synth = (esi & F_SYNTH) !== 0;
    const rel = (esi & F_RELEASE) !== 0;
    let holdTime = 0;
    for (let b = 0; b < 16; b++) {
      if (esi & (1 << b)) {
        if (!rel) this.pressTime[b] = time;
        else holdTime = time - this.pressTime[b]!;
        break;
      }
    }
    if (esi) {
      const low = esi & 0xffff;
      if (low === K_U || low === K_F || low === K_D || low === K_B) {
        const now = this.heldDirs();
        const prev = this.dirState;
        if (now !== prev) {
          if (prev) this.push(prev | F_RELEASE, time, holdTime);
          esi = now;
          if (rel && synth) esi |= F_SYNTH;
          this.dirState = now;
        }
      }
    }
    if (esi & 0x9f000) {
      if (esi & 0xffff) this.push(esi, time, holdTime);
      return;
    }
    if (esi) {
      // Button press: wait for a tick without events (or more presses).
      this.pending |= esi;
      return;
    }
    if (this.pending) {
      const p = this.pending;
      this.pending = 0;
      if (p & 0xffff) this.push(p, time, holdTime);
    }
  }

  /** mugen.exe 0x4787e0. */
  private process(time: number): void {
    const cmds = this.set.commands;
    while (this.qRead !== this.qWrite) {
      this.qRead = (this.qRead + 1) % QUEUE;
      for (const c of cmds) {
        const start = this.match(c);
        if (start !== undefined && start > this.last[c.slot]!) {
          this.buffer[c.slot] = c.bufferTime;
          this.last[c.slot] = time;
        }
      }
    }
    for (const c of cmds) {
      if (c.elements.length !== 1 || !(c.elements[0]!.bits & F_HOLD)) continue;
      if (this.match(c) !== undefined) {
        this.buffer[c.slot] = 1;
        this.last[c.slot] = time;
      }
    }
  }

  /** mugen.exe 0x478a50: does element `el` match queue entry `j`? */
  private elementMatches(el: number, j: number): boolean {
    if (el & F_HOLD) {
      const d = el & DIR_BITS;
      if (d) {
        let c = this.heldBits & DIR_BITS;
        if (d & 0x80000 && c === 0) return true;
        if (el & F_LOOSE) c &= d;
        return c === d;
      }
      return (el & 0xfff) !== 0 && (this.heldBits & el & 0xfff) !== 0;
    }
    const ev = this.qBits[j]!;
    if (this.qHold[j]! < ((el >> 20) & ~3)) return false;
    const rel = ev & F_RELEASE;
    if (!rel && ev & F_SYNTH) return false;
    if (el & DIR_BITS) {
      const d = el & 0x1ffff;
      if (el & F_LOOSE) return (ev & d) === d && (d & F_RELEASE) === rel;
      return ev === d;
    }
    if (!(el & 0xfff)) return false;
    if ((el & F_RELEASE) !== rel) return false;
    const m = el & 0xffff;
    return (ev & m) === m;
  }

  /** mugen.exe 0x478b30: start time of the match ending at the newest entry. */
  private match(c: Command): number | undefined {
    const els = c.elements;
    let k = els.length - 1;
    const cur = (this.qRead + QUEUE - 1) % QUEUE;
    const tNow = this.qTime[cur]!;
    if (!this.elementMatches(els[k]!.bits, cur)) return undefined;
    let j = this.qRead;
    if (j === this.qStart) return undefined;
    let strict = false;
    for (;;) {
      j = (j + QUEUE - 1) % QUEUE;
      const elapsed = tNow - this.qTime[j]!;
      if (elapsed > c.time && !(els[k]!.bits & F_HOLD)) return undefined;
      if (this.elementMatches(els[k]!.bits, j)) {
        strict = els[k]!.strict;
        k--;
        if (k < 0) return this.qTime[j]!;
      } else {
        if (strict) return undefined;
        strict = false;
      }
      if (elapsed > c.time && !(els[k]!.bits & F_HOLD)) return undefined;
      if (j === this.qStart) return undefined;
    }
  }
}
