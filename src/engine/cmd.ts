// MUGEN's per-player input pipeline.

/** Key indices in events: 1 U, 2 F, 3 D, 4 B, 5..11 a b c x y z s. */
const KEY_BITS = [0, K_U, K_F, K_D, K_B, 0x10, 0x20, 0x40, 0x80, 0x100, 0x200, 0x400];
const EV_RELEASE = 0x10;
const EV_SYNTH = 0x20;
/**
 * Absolute input bits in the order the harness (and so our replay) sends
 * simultaneous key changes: alphabetically by key name (a b c d l r s u x y z).
 */
const KEY_ORDER: [number, number | 'R' | 'L'][] = [
  [IN_A, 5], [IN_B, 6], [IN_C, 7], [IN_D, 3], [IN_L, 'L'], [IN_R, 'R'], [IN_S, 11], [IN_U, 1], [IN_X, 8], [IN_Y, 9], [IN_Z, 10],
];
const RING = 30;
const QUEUE = 128;

export class CommandInput {
  /**
   * Held flags by key index (relative: index 2 = forward, 4 = back). MUGEN's
   * array is 1-based with 11 keys; the AI's release loops run to 13, where
   * slot 13 aliases the ring's read index (see heldAt / setHeld).
   */
  private held = new Uint8Array(13);
  private facingLeft = false;
  private prevRaw = 0;
  // 30-entry key event ring with MUGEN's read/write indices.
  private ring = new Int32Array(RING);
  private ringR = 0;
  private ringW = 0;
  private dirState = 0;
  private pending = 0;
  private pressTime = new Int32Array(16);
  // Command queue.
  private qBits = new Int32Array(QUEUE);
  private qTime = new Int32Array(QUEUE);
  private qHold = new Int32Array(QUEUE);
  private qStart = 0;
  private qWrite = 0;
  private qRead = 0;
  /** Held keys as bits, snapshot at the start of the tick (0x650). */
  private heldBits = 0;

  /**
   * This tick's consumed key event is an Up press (air jump; measured: a CPU
   * release-and-press of U in one tick air-jumps when the press is consumed).
   */
  upPressed = false;
  private buffer: Uint8Array;
  private last: Float64Array;

  /**
   * Switch to another command list (custom states): the active labels are
   * cleared, their last activation frames kept.
   */
  useSet(set: CommandSet): void {
    if (set === this.set) return;
    this.set = set;
    this.buffer = new Uint8Array(Math.max(1, set.size));
    const last = new Float64Array(Math.max(1, set.size)).fill(-Infinity);
    last.set(this.last.subarray(0, Math.min(this.last.length, last.length)));
    this.last = last;
  }

  /** The command list in use. */
  get commandSet(): CommandSet {
    return this.set;
  }

  constructor(private set: CommandSet) {
    this.buffer = new Uint8Array(Math.max(1, set.size));
    this.last = new Float64Array(Math.max(1, set.size)).fill(-Infinity);
  }

  /**
   * MUGEN's command count. The AI injects a random index below it; an index
   * with no name (the number "recovery" skipped) does nothing (measured with
   * KFM: 34 names numbered 0..34).
   */
  get commandCount(): number {
    return this.set.slots;
  }

  /**
   * One tick for a human player: facing-change events, this tick's key
   * events, then the player's update (one event consumed, queue matched).
   */
  tick(raw: number, facing: number, time: number, frozen: boolean): void {
    this.ingest(raw, facing, true);
    this.update(time, frozen);
  }

  /** First half of the tick: facing sync, then OS key events (humans only). */
  ingest(raw: number, facing: number, human: boolean): void {
    this.syncFacing(facing < 0);
    if (human) this.keyEvents(raw);
  }

  /**
   * A copy with its own buffers (a keyctrl helper starts with its root's
   * input and command state: Helper_Create copies p->input and cmd_state).
   */
  clone(): CommandInput {
    const c = new CommandInput(this.set);
    for (const [k, v] of Object.entries(this)) {
      (c as unknown as Record<string, unknown>)[k] = ArrayBuffer.isView(v) ? (v as Uint8Array).slice() : Array.isArray(v) ? v.slice() : v;
    }
    return c;
  }

  /** Whether command slot n is active (buffer > 0). */
  slotActive(n: number): boolean {
    return (this.buffer[n] ?? 0) > 0;
  }

  /** Active command names (buffer > 0). */
  active(): Set<string> {
    const out = new Set<string>();
    for (const c of this.set.commands) if (this.buffer[c.slot]! > 0) out.add(c.name);
    return out;
  }

  /** Debug: [read, write, ring x30, held 1..11] in MUGEN's layout. */
  debugState(): number[] {
    return [this.ringR, this.ringW, ...this.ring, ...Array.from(this.held.slice(1, 12))];
  }

  /** held[k] as MUGEN reads it (k = 13 is the ring's read index). */
  heldAt(k: number): number {
    if (k === 13) return this.ringR;
    return this.held[k] ?? 0;
  }

  /** mugen.exe 0x477d00: push a key event and update the held flag. */
  pushKey(code: number): void {
    const k = code & 0xf;
    if (!k) return;
    this.ring[this.ringW] = code;
    this.ringW = (this.ringW + 1) % RING;
    if (this.ringW === this.ringR) this.ringR = (this.ringR + 1) % RING;
    const v = (code & EV_RELEASE) ? 0 : 1;
    if (k === 13) this.ringR = v;
    else this.held[k] = v;
  }

  private popKey(): number {
    if (this.ringR === this.ringW) return 0;
    const v = this.ring[this.ringR]!;
    this.ringR = (this.ringR + 1) % RING;
    return v;
  }

  private pushEvent(code: number): void {
    this.pushKey(code);
  }

  /** mugen.exe 0x477c40: turning around swaps a held forward/back key. */
  /** Facing change: held forward/back swap through synthetic key events. */
  syncFacing(left: boolean): void {
    if (left === this.facingLeft) return;
    const wasLeft = this.facingLeft;
    this.facingLeft = left;
    if (this.held[2] && this.held[4]) return;
    const first = wasLeft ? 2 : 4;
    const other = wasLeft ? 4 : 2;
    if (this.held[first]) {
      this.pushEvent(EV_SYNTH | EV_RELEASE | first);
      this.pushEvent(EV_SYNTH | other);
    } else if (this.held[other]) {
      this.pushEvent(EV_SYNTH | EV_RELEASE | other);
      this.pushEvent(EV_SYNTH | first);
    }
  }

  /** OS key events for what changed since last tick: releases, then presses. */
  private keyEvents(raw: number): void {
    const changed = raw ^ this.prevRaw;
    if (!changed) return;
    const idxOf = (k: number | 'R' | 'L') => (k === 'R' ? (this.facingLeft ? 4 : 2) : k === 'L' ? (this.facingLeft ? 2 : 4) : k);
    for (const [bit, k] of KEY_ORDER) if (changed & bit && !(raw & bit)) this.pushEvent(EV_RELEASE | idxOf(k));
    for (const [bit, k] of KEY_ORDER) if (changed & bit && raw & bit) this.pushEvent(idxOf(k));
    this.prevRaw = raw;
  }

  private heldDirs(): number {
    return (this.held[1] ? K_U : 0) | (this.held[2] ? K_F : 0) | (this.held[4] ? K_B : 0) | (this.held[3] ? K_D : 0);
  }

  /** mugen.exe 0x434db0 (input part). */
  /** Key event consumed this tick (0 if none). */
  lastEvent = 0;

  /**
   * mugen.exe 0x434db0 (input part). `aiCmds` (command indices pushed by the
   * CPU this tick) are set after matching, active for this tick only (0x42f750).
   */
  update(time: number, floor2: boolean, aiCmds?: readonly number[], holdBuffers = false): void {
    const ev = this.popKey();
    this.lastEvent = ev;
    let held = 0;
    for (let i = 1; i < 12; i++) if (this.held[i]) held |= KEY_BITS[i]!;
    this.heldBits = held;
    const floor = floor2 ? 2 : 0;
    // In hit pause the buffers do not count down (mugen.exe 0x434fbc), so a
    // command entered during the pause fires when it ends (measured).
    if (!holdBuffers) for (let i = 0; i < this.buffer.length; i++) {
      if (this.buffer[i]! > 0) {
        this.buffer[i]!--;
        if (this.buffer[i]! < floor) this.buffer[i] = floor;
      }
    }
    // A consumed Up press event, even with Up already counted as held.
    this.upPressed = (ev & 0xf) === 1 && !(ev & EV_RELEASE);
    this.produce(ev, time);
    this.process(time);
    if (aiCmds) for (const i of aiCmds) if (i >= 0 && i < this.buffer.length) this.buffer[i] = 1;
  }

  private push(bits: number, time: number, hold: number): void {
    this.qBits[this.qWrite] = bits;
    this.qTime[this.qWrite] = time;
    this.qHold[this.qWrite] = hold;
    this.qWrite = (this.qWrite + 1) % QUEUE;
    if (this.qWrite === this.qStart) this.qStart = (this.qStart + 1) % QUEUE;
  }

  /** mugen.exe 0x478610: turn one key event (or none) into queue entries. */
  private produce(ev: number, time: number): void {
    let esi = 0;
    if (ev) {
      esi = KEY_BITS[ev & 0xf] ?? 0;
      if (ev & EV_RELEASE) esi |= F_RELEASE;
      if (ev & EV_SYNTH) esi |= F_SYNTH;
    }
    const synth = (esi & F_SYNTH) !== 0;
    const rel = (esi & F_RELEASE) !== 0;
    let holdTime = 0;
    for (let b = 0; b < 16; b++) {
      if (esi & (1 << b)) {
        if (!rel) this.pressTime[b] = time;
        else holdTime = time - this.pressTime[b]!;
        break;
      }
    }
    if (esi) {
      const low = esi & 0xffff;
      if (low === K_U || low === K_F || low === K_D || low === K_B) {
        const now = this.heldDirs();
        const prev = this.dirState;
        if (now !== prev) {
          if (prev) this.push(prev | F_RELEASE, time, holdTime);
          esi = now;
          if (rel && synth) esi |= F_SYNTH;
          this.dirState = now;
        }
      }
    }
    if (esi & 0x9f000) {
      if (esi & 0xffff) this.push(esi, time, holdTime);
      return;
    }
    if (esi) {
      // Button press: wait for a tick without events (or more presses).
      this.pending |= esi;
      return;
    }
    if (this.pending) {
      const p = this.pending;
      this.pending = 0;
      if (p & 0xffff) this.push(p, time, holdTime);
    }
  }

  /** mugen.exe 0x4787e0. */
  private process(time: number): void {
    const cmds = this.set.commands;
    while (this.qRead !== this.qWrite) {
      this.qRead = (this.qRead + 1) % QUEUE;
      for (const c of cmds) {
        const start = this.match(c);
        if (start !== undefined && start > this.last[c.slot]!) {
          this.buffer[c.slot] = c.bufferTime;
          this.last[c.slot] = time;
        }
      }
    }
    for (const c of cmds) {
      if (c.elements.length !== 1 || !(c.elements[0]!.bits & F_HOLD)) continue;
      if (this.match(c) !== undefined) {
        this.buffer[c.slot] = 1;
        this.last[c.slot] = time;
      }
    }
  }

  /** mugen.exe 0x478a50: does element `el` match queue entry `j`? */
  private elementMatches(el: number, j: number): boolean {
    if (el & F_HOLD) {
      const d = el & DIR_BITS;
      if (d) {
        let c = this.heldBits & DIR_BITS;
        if (d & 0x80000 && c === 0) return true;
        if (el & F_LOOSE) c &= d;
        return c === d;
      }
      return (el & 0xfff) !== 0 && (this.heldBits & el & 0xfff) !== 0;
    }
    const ev = this.qBits[j]!;
    if (this.qHold[j]! < ((el >> 20) & ~3)) return false;
    const rel = ev & F_RELEASE;
    if (!rel && ev & F_SYNTH) return false;
    if (el & DIR_BITS) {
      const d = el & 0x1ffff;
      if (el & F_LOOSE) return (ev & d) === d && (d & F_RELEASE) === rel;
      return ev === d;
    }
    if (!(el & 0xfff)) return false;
    if ((el & F_RELEASE) !== rel) return false;
    const m = el & 0xffff;
    return (ev & m) === m;
  }

  /** mugen.exe 0x478b30: start time of the match ending at the newest entry. */
  private match(c: Command): number | undefined {
    const els = c.elements;
    let k = els.length - 1;
    const cur = (this.qRead + QUEUE - 1) % QUEUE;
    const tNow = this.qTime[cur]!;
    if (!this.elementMatches(els[k]!.bits, cur)) return undefined;
    let j = this.qRead;
    if (j === this.qStart) return undefined;
    let strict = false;
    for (;;) {
      j = (j + QUEUE - 1) % QUEUE;
      const elapsed = tNow - this.qTime[j]!;
      if (elapsed > c.time && !(els[k]!.bits & F_HOLD)) return undefined;
      if (this.elementMatches(els[k]!.bits, j)) {
        strict = els[k]!.strict;
        k--;
        if (k < 0) return this.qTime[j]!;
      } else {
        if (strict) return undefined;
        strict = false;
      }
      // Cmd_Match's second window test is the other way round: past the
      // time, a hold step ends the search (mugen.exe 0x478c22: test 0x20000, jne).
      if (elapsed > c.time && els[k]!.bits & F_HOLD) return undefined;
      if (j === this.qStart) return undefined;
    }
  }
}
